"""Generate runnable pytest files from scan findings.

The most valuable output of ``mltk scan``: self-contained pytest files
that reproduce every issue the scan found.  A developer runs the scan
once, gets a test file, and from that point on CI catches regressions
automatically -- no manual test-writing needed.

Scanner ``suggested_test`` values are zero-indented test bodies.  They may
use the names in :data:`SNIPPET_PROVIDED_NAMES` and public attributes of
the top-level :mod:`mltk` package; the generator supplies the corresponding
fixtures, prelude statements, and imports.

The generated code is:

- **Self-contained**: all imports, fixtures, and model loading in one
  file.  Copy it anywhere and ``pytest`` just works.
- **Environment-friendly**: model and data paths fall back to
  ``MLTK_MODEL_PATH`` / ``MLTK_DATA_PATH`` environment variables so
  the same file works locally and in CI.
- **Validated**: every generated file is parsed with ``ast.parse()``
  before being returned -- syntax errors are caught immediately,
  never shipped to the user.

Example::

    from mltk.scan.codegen import generate_test_file

    code = generate_test_file(
        findings,
        model_path="model.pkl",
        data_path="data.csv",
        target_col="label",
    )
    # code is a valid Python string ready for pytest
"""

from __future__ import annotations

import ast
import os
import re
import textwrap
from typing import TYPE_CHECKING

if TYPE_CHECKING:
    from mltk.scan.finding import ScanFinding

SNIPPET_PROVIDED_NAMES: frozenset[str] = frozenset({
    "model", "data", "X", "y", "y_pred", "model_fn",
    "X_train", "y_train", "np", "pd", "pytest",
})

__all__ = [
    "SNIPPET_PROVIDED_NAMES",
    "check_snippet",
    "generate_test_file",
]

# ------------------------------------------------------------------
# Severity ordering for deterministic test output
# ------------------------------------------------------------------
_SEVERITY_ORDER = {"critical": 0, "warning": 1, "info": 2}


# ------------------------------------------------------------------
# Internal helpers
# ------------------------------------------------------------------

def _sanitize_name(raw: str) -> str:
    """Turn an arbitrary string into a valid Python identifier.

    Strips non-alphanumeric characters, collapses runs of
    underscores, and ensures the result starts with a letter.
    """
    cleaned = re.sub(r"[^a-zA-Z0-9]", "_", raw)
    cleaned = re.sub(r"_+", "_", cleaned).strip("_")
    if not cleaned or not cleaned[0].isalpha():
        cleaned = "t_" + cleaned
    return cleaned.lower()


def _build_header() -> str:
    """Return the file-level docstring and imports block."""
    return textwrap.dedent("""\
        \"\"\"Auto-generated by mltk scan.

        Each test reproduces one issue found during scanning.
        Re-run this file with pytest.
        \"\"\"

        from __future__ import annotations

        import os

        import numpy as np
        import pandas as pd
        import pytest
    """)


def _build_read_table_helper() -> str:
    """Return the CSV/parquet reader shared by the data fixtures."""
    return textwrap.dedent("""\

        def _read_table(path):
            \"\"\"Read CSV or parquet, matching ``mltk scan-model --data``.\"\"\"
            if str(path).lower().endswith(".parquet"):
                return pd.read_parquet(path)
            return pd.read_csv(path)
    """)


def _snippet_names(body: str) -> tuple[set[str], set[str]]:
    """Return loaded names and names assigned anywhere in *body*."""
    try:
        tree = ast.parse(body, mode="exec")
    except SyntaxError as exc:
        raise ValueError(f"invalid scanner snippet syntax: {exc.msg}") from exc

    for node in ast.walk(tree):
        if isinstance(node, (ast.Import, ast.ImportFrom)):
            raise ValueError("scanner snippet contains an import")
    for node in tree.body:
        if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef)):
            raise ValueError(
                "scanner snippet contains a top-level "
                f"{type(node).__name__}"
            )

    loaded = {
        node.id for node in ast.walk(tree)
        if isinstance(node, ast.Name) and isinstance(node.ctx, ast.Load)
    }
    assigned = {
        node.id for node in ast.walk(tree)
        if isinstance(node, ast.Name) and isinstance(node.ctx, ast.Store)
    }
    return loaded, assigned


def check_snippet(body: str) -> None:
    """Validate a scanner test body against the codegen contract."""
    loaded, assigned = _snippet_names(body)
    import builtins

    unknown = sorted(
        name for name in loaded - assigned
        if name not in SNIPPET_PROVIDED_NAMES
        and name not in builtins.__dict__
    )
    if unknown:
        import mltk

        invalid = [name for name in unknown if not hasattr(mltk, name)]
        if invalid:
            raise ValueError(
                "scanner snippet uses unknown name(s): "
                + ", ".join(invalid)
            )


def _build_model_fixture(
    model_path: str | None,
) -> str:
    """Return a pytest fixture that loads the model.

    Falls back to the ``MLTK_MODEL_PATH`` env var when no
    literal path was provided at generation time.
    """
    if model_path is not None:
        literal = repr(str(model_path))
    else:
        literal = "None"

    return textwrap.dedent(f"""\

        @pytest.fixture(scope="module")
        def model():
            \"\"\"Load the scanned model with the scan's own loader.

            Override with MLTK_MODEL_PATH env var.  Returns an object
            with ``predict`` (and ``predict_proba`` when supported).
            \"\"\"
            from types import SimpleNamespace

            from mltk.scan.loader import load_model

            path = os.environ.get(
                "MLTK_MODEL_PATH", {literal},
            )
            if path is None:
                pytest.skip(
                    "Set MLTK_MODEL_PATH or pass --model"
                )
            loaded = load_model(path)
            return SimpleNamespace(
                predict=loaded.predict_fn,
                predict_proba=loaded.predict_proba_fn,
                raw=loaded.raw,
            )
    """)


def _build_data_fixture(
    data_path: str | None,
    target_col: str | None,
) -> str:
    """Return a pytest fixture that loads X and y.

    Falls back to the ``MLTK_DATA_PATH`` env var.  The target
    column defaults to ``"target"`` if not specified.
    """
    if data_path is not None:
        literal = repr(str(data_path))
    else:
        literal = "None"

    col = target_col if target_col else "target"

    return textwrap.dedent(f"""\

        @pytest.fixture(scope="module")
        def data():
            \"\"\"Load the scanned dataset.

            Override with MLTK_DATA_PATH env var.
            Returns (X, y) tuple.
            \"\"\"
            path = os.environ.get(
                "MLTK_DATA_PATH", {literal},
            )
            if path is None:
                pytest.skip(
                    "Set MLTK_DATA_PATH or pass --data"
                )
            df = _read_table(path)
            target = {repr(col)}
            y = df[target].values
            X = df.drop(columns=[target])
            return X, y
    """)


def _build_test_method(
    index: int,
    finding: ScanFinding,
) -> str:
    """Build a single test method from a ScanFinding.

    Uses ``suggested_test`` when the scanner provided one.
    Otherwise falls back to a generic assertion based on the
    finding's result fields.
    """
    result = finding.result
    severity = result.severity.value
    safe_name = _sanitize_name(result.name)
    method_name = f"test_{index:03d}_{safe_name}"

    # Docstring from the finding.  Escape backslashes and quotes so a
    # message such as "slice C:\Users" cannot break the literal.
    docstring = (
        f"{result.message}\n\n"
        f"Scanner: {finding.scanner_name}\n"
        f"Severity: {severity}"
    ).replace("\\", "\\\\").replace('"', '\\"')
    # Indent continuation lines to the docstring; keep blank lines empty.
    docstring = "\n".join(
        f"        {line}" if line else ""
        for line in docstring.split("\n")
    ).lstrip()

    body = _finding_body(finding)
    loaded, _assigned = _snippet_names(body)
    needs_train = bool(loaded & {"X_train", "y_train"})
    params = "model, data"
    if needs_train:
        params += ", train_data"

    lines = [
        f"    def {method_name}(self, {params}):",
        f'        """{docstring}"""',
        "        X, y = data",
    ]
    if "y_pred" in loaded:
        lines.append("        y_pred = model.predict(X)")
    if "model_fn" in loaded:
        lines.append("        model_fn = model.predict")
    if needs_train:
        lines.append("        X_train, y_train = train_data")
    # Indent the body relative to the method
    for line in body.splitlines():
        lines.append(f"        {line}")

    return "\n".join(lines)


def _finding_body(finding: ScanFinding) -> str:
    """Return the contract-checked test body for *finding*.

    Uses ``suggested_test`` when it satisfies :func:`check_snippet`.
    A violating snippet degrades to the generic failing body (with the
    reason as a comment) so one bad finding cannot abort the whole file.
    """
    if not finding.suggested_test.strip():
        return _generic_body(finding)
    body = finding.suggested_test.rstrip()
    try:
        check_snippet(body)
    except ValueError as exc:
        reason = str(exc).replace("\n", " ")
        return f"# Scanner snippet rejected: {reason}\n" + _generic_body(finding)
    return body


def _generic_body(finding: ScanFinding) -> str:
    """Produce a fallback test body when no suggested_test."""
    result = finding.result
    details = result.details or {}

    parts: list[str] = [
        "# Auto-generated: verify this finding",
    ]

    if "metric" in details and "threshold" in details:
        metric = details["metric"]
        threshold = details["threshold"]
        parts.append(
            f"# Expected {metric} >= {threshold}"
        )
    parts.append(
        f"assert False, {repr(result.message)}"
    )
    return "\n".join(parts)


def _build_class(
    findings: list[ScanFinding],
) -> str:
    """Build the TestScanFindings class with all methods."""
    sorted_findings = sorted(
        findings,
        key=lambda f: _SEVERITY_ORDER.get(
            f.result.severity.value, 99
        ),
    )

    methods: list[str] = []
    for i, finding in enumerate(sorted_findings, start=1):
        methods.append(
            _build_test_method(i, finding),
        )

    body = "\n\n".join(methods)
    return (
        "\n\nclass TestScanFindings:\n"
        '    """Tests generated by mltk scan."""\n\n'
        f"{body}\n"
    )


def _mltk_names(findings: list[ScanFinding]) -> set[str]:
    """Return public mltk attributes referenced by all finding bodies."""
    import mltk

    names: set[str] = set()
    for finding in findings:
        loaded, assigned = _snippet_names(_finding_body(finding))
        names.update(
            name for name in loaded - assigned
            if name not in SNIPPET_PROVIDED_NAMES
            and hasattr(mltk, name)
        )
    return names


def _build_train_data_fixture(
    train_data_path: str | None,
    target_col: str | None,
) -> str:
    """Return the optional training-data fixture."""
    literal = repr(str(train_data_path)) if train_data_path is not None else "None"
    col = target_col if target_col else "target"
    return textwrap.dedent(f"""\

        @pytest.fixture(scope="module")
        def train_data():
            path = os.environ.get("MLTK_TRAIN_DATA_PATH", {literal})
            if path is None:
                pytest.skip("Set MLTK_TRAIN_DATA_PATH to run train/test checks")
            df = _read_table(path)
            target = {repr(col)}
            return df.drop(columns=[target]), df[target].values
    """)


def _validate_syntax(code: str) -> None:
    """Parse *code* with ``ast.parse`` to catch syntax errors.

    Raises:
        SyntaxError: If the generated code is not valid Python.
    """
    ast.parse(code, filename="<mltk-codegen>")


# ------------------------------------------------------------------
# Public API
# ------------------------------------------------------------------

def generate_test_file(
    findings: list[ScanFinding],
    model_path: str | None = None,
    data_path: str | None = None,
    target_col: str | None = None,
    output_path: str | None = None,
    train_data_path: str | None = None,
) -> str:
    """Generate a self-contained pytest file from scan findings.

    The generated file includes everything needed to run
    standalone:

    - All necessary imports (numpy, pandas, pytest, joblib).
    - A ``model`` fixture that loads the scanned model, with
      ``MLTK_MODEL_PATH`` env-var fallback.
    - A ``data`` fixture that loads the dataset and splits X/y,
      with ``MLTK_DATA_PATH`` env-var fallback.
    - One test method per finding inside a
      ``TestScanFindings`` class.
    - Methods ordered by severity (CRITICAL first).

    The complete source is validated with ``ast.parse()`` before
    returning.  If a scanner produced invalid ``suggested_test``
    code, this function raises ``SyntaxError`` immediately --
    broken tests are never written to disk.

    Args:
        findings: List of ScanFinding objects from a scan run.
            An empty list produces a file with fixtures but no
            test methods (useful as a template).
        model_path: Filesystem path to the model file
            (e.g., ``"model.pkl"``).  Baked into the fixture as
            a default; overridable via ``MLTK_MODEL_PATH``.
        data_path: Filesystem path to the CSV dataset.  Baked
            into the fixture as a default; overridable via
            ``MLTK_DATA_PATH``.
        target_col: Name of the target/label column in the CSV.
            Defaults to ``"target"`` when not specified.
        train_data_path: Optional training CSV path for findings
            that reference ``X_train`` or ``y_train``.  Falls back
            to ``MLTK_TRAIN_DATA_PATH``.
        output_path: If provided, the generated code is also
            written to this file.  Parent directories are
            created automatically.

    Returns:
        The generated Python source code as a string.

    Raises:
        SyntaxError: If the assembled code fails ``ast.parse()``.

    Example::

        from mltk.scan.codegen import generate_test_file

        code = generate_test_file(
            report.findings,
            model_path="models/clf.pkl",
            data_path="data/test.csv",
            target_col="label",
            output_path="tests/test_scan_results.py",
        )
        print(f"Generated {len(code)} chars of test code")
    """
    mltk_names = _mltk_names(findings)
    needs_train = any(
        _snippet_names(_finding_body(f))[0] & {"X_train", "y_train"}
        for f in findings
    )
    parts: list[str] = [
        _build_header(),
        (
            "from mltk import " + ", ".join(sorted(mltk_names)) + "\n"
            if mltk_names else ""
        ),
        _build_read_table_helper(),
        _build_model_fixture(model_path),
        _build_data_fixture(data_path, target_col),
    ]
    if needs_train:
        parts.append(_build_train_data_fixture(train_data_path, target_col))

    if findings:
        parts.append(_build_class(findings))
    else:
        parts.append(
            "\n\n# No findings -- scan was clean.\n"
        )

    code = "\n".join(parts)

    # Gate: never return invalid Python
    _validate_syntax(code)

    if output_path is not None:
        parent = os.path.dirname(output_path)
        if parent:
            os.makedirs(parent, exist_ok=True)
        with open(output_path, "w", encoding="utf-8") as fh:
            fh.write(code)

    return code
